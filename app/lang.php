function ltText(string $key, array $params = []): string
{
    $text = LT_MESSAGES[$key];
    return $params === [] ? $text : strtr($text, array_combine(
        array_map(static fn(string $name): string => '{'.$name.'}', array_keys($params)),
        array_values($params)
    ));
}

function ltOption(string $value): string
{
    return LT_OPTIONS[$value] ?? $value;
}

function ltDate(DateTimeInterface $date, string $key): string
{
    return ltText($key, [
        'weekday' => ltOption($date->format('l')),
        'month' => ltOption($date->format('F')),
        'short_month' => ltOption($date->format('M')),
        'day' => $date->format('j'),
        'year' => $date->format('Y'),
        'time' => $date->format('H:i'),
    ]);
}
